    private void btnEditarProdutoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarProdutoActionPerformed
        int linhaSelecionada = TabelaProdutos.getSelectedRow();
    
   
    if (linhaSelecionada != -1) {
        int idProduto = (int) TabelaProdutos.getValueAt(linhaSelecionada, 0);
        String nomeAtual = (String) TabelaProdutos.getValueAt(linhaSelecionada, 1);
        double precoAtual = (double) TabelaProdutos.getValueAt(linhaSelecionada, 2);
        int estoqueAtual = (int) TabelaProdutos.getValueAt(linhaSelecionada, 3);
        
        try {
            String novoNome = JOptionPane.showInputDialog(this, "Novo Nome do Produto:", nomeAtual);
            String novoPrecoStr = JOptionPane.showInputDialog(this, "Novo Preço Unitário:", precoAtual);
            String novoEstoqueStr = JOptionPane.showInputDialog(this, "Nova Quantidade em Estoque:", estoqueAtual);
            
            
            if (novoNome != null && novoPrecoStr != null && novoEstoqueStr != null) {
                double novoPreco = Double.parseDouble(novoPrecoStr);
                int novoEstoque = Integer.parseInt(novoEstoqueStr);
                
                Produto p = new Produto();
                p.setId(idProduto);
                p.setNome(novoNome);
                p.setPreco(novoPreco);
                p.setEstoque(novoEstoque);
                
                ProdutoDAO dao = new ProdutoDAO();
                if (dao.atualizar(p)) {
                    JOptionPane.showMessageDialog(this, "Produto atualizado com sucesso!");
                    carregarTabelaProdutos(); 
                } else {
                    JOptionPane.showMessageDialog(this, "Erro ao atualizar o produto no banco.");
                }
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro nos valores numéricos digitados. Verifique o preço e o estoque.");
        }
    } else {
        JOptionPane.showMessageDialog(this, "Selecione um produto na tabela para editar.");
    }
    }//GEN-LAST:event_btnEditarProdutoActionPerformed


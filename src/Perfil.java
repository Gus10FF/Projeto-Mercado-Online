      public void carregarTabelaProdutos() {
        DefaultTableModel modelo = new DefaultTableModel(new Object[]{"ID", "Nome do Produto", "Preço (R$)", "Estoque"}, 0);
        ProdutoDAO dao = new ProdutoDAO();
        List<Produto> lista = dao.listarPorParticipante(participanteLogado.getId());

        for (Produto p : lista) {
            modelo.addRow(new Object[]{p.getId(), p.getNome(), p.getPreco(), p.getEstoque()});
        }
        TabelaProdutos.setModel(modelo);
    }
      
      
    

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
       String novoNome = JOptionPane.showInputDialog(this, "Novo Nome:", participanteLogado.getNome());
        String novoEmail = JOptionPane.showInputDialog(this, "Novo E-mail:", participanteLogado.getEmail());
        
        if (novoNome != null && novoEmail != null) {
            participanteLogado.setNome(novoNome);
            participanteLogado.setEmail(novoEmail);
            
            ParticipanteDAO dao = new ParticipanteDAO();
            if (dao.atualizar(participanteLogado)) {
                JOptionPane.showMessageDialog(this, "Perfil atualizado com sucesso!");
                
                lblNome.setText(participanteLogado.getNome());
                
            } else {
                JOptionPane.showMessageDialog(this, "Erro ao atualizar perfil.");
            }
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        int confirm = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir sua conta permanentemente?", "Atenção", JOptionPane.YES_NO_OPTION);
        if (confirm == JOptionPane.YES_OPTION) {
            ParticipanteDAO dao = new ParticipanteDAO();
            if (dao.excluir(participanteLogado.getId())) {
                JOptionPane.showMessageDialog(this, "Conta excluída com sucesso.");
                this.dispose();
            
            }
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

